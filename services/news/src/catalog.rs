//! The news desks this service follows: outlets, and sections of them.

use crate::topic::{self, Topic};

/// A feed of one outlet, or of one of its sections.
pub struct Desk {
    /// `{outlet}`, or `{outlet}/{section}`, the section as deep as the
    /// outlet's own structure (`google/blog/ai`). What an `Article` names it.
    pub key: &'static str,
    /// The outlet's name, shared by its desks.
    pub outlet: &'static str,
    /// The desk's name within its outlet: `Technology`, or `Latest` for an
    /// outlet's main feed.
    pub name: &'static str,
    pub reader: Reader,
    /// The page a person reads it on.
    pub home: &'static str,
    /// What a reader following it gets.
    pub description: &'static str,
    /// The beats it covers.
    pub topics: &'static [Topic],
}

/// How a desk is read.
pub enum Reader {
    /// An RSS or Atom feed.
    Feed(&'static str),
    /// An index page whose links starting with `link_prefix` are its
    /// articles, dated by a `<time>` inside the link and titled by each
    /// article's `og:title`.
    Page {
        index: &'static str,
        link_prefix: &'static str,
    },
}

impl Desk {
    /// The desk keyed `key`.
    pub fn find(key: &str) -> Option<&'static Desk> {
        DESKS.iter().find(|desk| desk.key == key)
    }
}

